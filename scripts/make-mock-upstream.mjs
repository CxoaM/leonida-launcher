#!/usr/bin/env node
/**
 * Builds a throwaway "upstream" repository for manual verification.
 *
 * The launcher has exactly one real upstream (ubiquitarianism/leonida). This
 * script does not copy it, download it or pretend to be it. It creates a small
 * git repository with the same *shape* the integration layer probes, so the
 * installation, compatibility and build screens can be exercised without a
 * 300 GB asset pipeline:
 *
 *   - make_game.py with the flags and stage list the adapter expects
 *   - .gitmodules + third_party/rpf9-explorer as a real submodule
 *   - tools/ and runtime/ directories
 *   - one or more commits, so upstream movement can be simulated
 *
 * Usage:
 *   npm run mock:upstream                       # create .tmp/upstream-fixture
 *   npm run mock:upstream -- --force            # recreate it from scratch
 *   npm run mock:upstream -- --add-commits 3    # simulate new upstream commits
 *   npm run mock:upstream -- --dest D:\fixture  # somewhere else
 *
 * Point Settings -> "Leonida checkout" at the generated folder to inspect the
 * UI. The launcher still refuses to *update* from it, because the remote is not
 * the official URL - that refusal is the intended behaviour, not a bug.
 */
import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function parseArgs(argv) {
  const args = {
    dest: path.join(root, ".tmp", "upstream-fixture"),
    force: false,
    addCommits: 0,
    submodule: true,
  };
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    switch (token) {
      case "--dest":
        args.dest = path.resolve(argv[++index] ?? args.dest);
        break;
      case "--force":
        args.force = true;
        break;
      case "--add-commits":
        args.addCommits = Number.parseInt(argv[++index] ?? "0", 10);
        break;
      case "--no-submodule":
        args.submodule = false;
        break;
      case "--help":
      case "-h":
        printUsage();
        process.exit(0);
      default:
        fail(`Unknown option: ${token}`);
    }
  }
  if (!Number.isInteger(args.addCommits) || args.addCommits < 0 || args.addCommits > 50) {
    fail("--add-commits expects a whole number between 0 and 50");
  }
  return args;
}

function printUsage() {
  console.log(
    [
      "Usage: npm run mock:upstream -- [options]",
      "",
      "  --dest <path>        Where to create the fixture (default: .tmp/upstream-fixture)",
      "  --force              Delete an existing fixture first",
      "  --add-commits <n>    Append n commits to an existing fixture",
      "  --no-submodule       Skip the third_party/rpf9-explorer submodule",
    ].join("\n"),
  );
}

function fail(message) {
  console.error(`mock:upstream: ${message}`);
  process.exit(1);
}

function git(cwd, args) {
  return execFileSync("git", args, {
    cwd,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  }).trim();
}

const MAKE_GAME = `#!/usr/bin/env python3
"""Fixture build entry point.

Generated by scripts/make-mock-upstream.mjs. It imitates the *shape* of the
upstream build entry point closely enough for the launcher's compatibility
probe, then does nothing. It is not Leonida: it never reads, writes or patches
game files.
"""
import argparse
import sys

STAGES = ["check", "shaders", "assets", "runtime", "pipelines"]


def main() -> int:
    parser = argparse.ArgumentParser(
        prog="make_game.py",
        description="Fixture build entry point used to test Leonida Launcher.",
        epilog="This fixture produces no game data. It only exercises the launcher.",
    )
    parser.add_argument("--game", help="folder that holds your own game package")
    parser.add_argument("--out", help="output folder")
    parser.add_argument("--work", help="work folder")
    parser.add_argument("--stages", help="comma list from: check,shaders,assets,runtime,pipelines")
    parser.add_argument("--jobs", type=int, default=0, help="parallel jobs (0 = automatic)")
    parser.add_argument("--no-tui", action="store_true", help="plain text output, no TUI")
    parser.add_argument("--check", action="store_true", help="validate inputs and stop")
    parser.add_argument("--find", action="store_true", help="locate a game package and exit")
    parser.add_argument("--pick", action="store_true", help="choose a package interactively")
    parser.add_argument(
        "--full-check",
        dest="full_check",
        action="store_true",
        help="validate every input before building",
    )
    parser.add_argument("--wav", action="store_true", help="write WAV files next to the output")
    parser.add_argument(
        "--wave64-emulate",
        choices=["auto", "on", "off"],
        default="auto",
        help="WAVE64 emulation mode",
    )
    parser.add_argument(
        "--runtime-build",
        dest="runtime_build",
        action="store_true",
        help="also build the runtime shim",
    )
    args = parser.parse_args()

    stages = [item.strip() for item in (args.stages or ",".join(STAGES)).split(",") if item.strip()]
    unknown = [item for item in stages if item not in STAGES]
    if unknown:
        parser.error("unknown stage(s): " + ", ".join(unknown))

    if args.find or args.pick:
        print("fixture: no game package here, this is a launcher fixture")
        return 0

    print(f"fixture: {len(stages)} stage(s), jobs={args.jobs}, wave64={args.wave64_emulate}")
    for index, stage in enumerate(stages, start=1):
        print(f"[{index}/{len(stages)}] {stage}: skipped (fixture)")
    print("fixture: nothing was built, no game files were touched")
    return 0


if __name__ == "__main__":
    sys.exit(main())
`;

const README = `# Leonida upstream fixture

This repository is generated by \`scripts/make-mock-upstream.mjs\`.

It is **not** Leonida, **not** a copy of Leonida, and contains no game data. It
exists so that Leonida Launcher can be exercised end to end — git detection,
submodule handling, the \`make_game.py --help\` compatibility probe and the build
streaming UI — without downloading hundreds of gigabytes of assets.

The launcher refuses to update from this remote because it is not the official
upstream URL. That refusal is correct behaviour.
`;

const BUILD_BAT = "@echo off\r\nrem Fixture wrapper for make_game.py.\r\npy -3 -I make_game.py %*\r\n";

async function writeAll(dest) {
  await mkdir(path.join(dest, "tools"), { recursive: true });
  await mkdir(path.join(dest, "runtime"), { recursive: true });
  await writeFile(path.join(dest, "make_game.py"), MAKE_GAME, "utf8");
  await writeFile(path.join(dest, "README.md"), README, "utf8");
  await writeFile(path.join(dest, "Build.bat"), BUILD_BAT, "utf8");
  await writeFile(path.join(dest, "tools", "README.md"), "Fixture placeholder for the toolkit folder.\n", "utf8");
  await writeFile(path.join(dest, "runtime", "README.md"), "Fixture placeholder for the runtime folder.\n", "utf8");
}

function commit(cwd, message) {
  git(cwd, ["add", "-A"]);
  git(cwd, ["-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid", "commit", "-m", message]);
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const dest = args.dest;

  if (path.parse(dest).root === dest || dest.split(path.sep).filter(Boolean).length < 3) {
    fail(`refusing to use ${dest} as a fixture folder; choose a deeper path`);
  }

  const exists = existsSync(dest);
  const isRepo = exists && existsSync(path.join(dest, ".git"));

  if (isRepo && args.addCommits > 0) {
    for (let index = 1; index <= args.addCommits; index += 1) {
      const stamp = new Date().toISOString();
      await writeFile(
        path.join(dest, "UPSTREAM-CHANGES.md"),
        `# Fixture changes\n\nSimulated upstream commit ${index} at ${stamp}.\n`,
        "utf8",
      );
      commit(dest, `Fixture: simulated upstream change ${index}`);
    }
    console.log(`Added ${args.addCommits} commit(s) to ${dest}`);
    console.log(`HEAD is now ${git(dest, ["rev-parse", "--short", "HEAD"])}`);
    return;
  }

  if (exists && !args.force) {
    fail(`${dest} already exists. Use --add-commits to extend it or --force to recreate it.`);
  }
  if (args.force) {
    await rm(dest, { recursive: true, force: true });
  }

  await writeAll(dest);
  git(dest, ["init", "-b", "main"]);
  git(dest, ["config", "user.name", "Fixture"]);
  git(dest, ["config", "user.email", "fixture@example.invalid"]);

  if (args.submodule) {
    const submoduleSource = `${dest}-rpf9`;
    await rm(submoduleSource, { recursive: true, force: true });
    await mkdir(submoduleSource, { recursive: true });
    await writeFile(
      path.join(submoduleSource, "README.md"),
      "Fixture stand-in for third_party/rpf9-explorer.\n",
      "utf8",
    );
    git(submoduleSource, ["init", "-b", "main"]);
    git(submoduleSource, ["config", "user.name", "Fixture"]);
    git(submoduleSource, ["config", "user.email", "fixture@example.invalid"]);
    commit(submoduleSource, "Fixture submodule");
    try {
      git(dest, [
        "-c",
        "protocol.file.allow=always",
        "submodule",
        "add",
        submoduleSource,
        "third_party/rpf9-explorer",
      ]);
    } catch (error) {
      console.warn(
        `warning: could not add the submodule (${error instanceof Error ? error.message : error})`,
      );
      console.warn("The fixture still works; the compatibility report will flag the missing submodule.");
    }
  }

  commit(dest, "Fixture: initial upstream snapshot");

  const head = git(dest, ["rev-parse", "HEAD"]);
  const readme = await readFile(path.join(dest, "README.md"), "utf8");

  console.log(
    [
      `Fixture ready at ${dest}`,
      `HEAD ${head}`,
      "",
      "Manual verification:",
      "  1. Start the launcher (npm run dev).",
      '  2. Settings -> "Leonida checkout" -> paste the path above.',
      "  3. Open Installation: it should detect the checkout and its submodule.",
      "  4. Open Build: the fixture documents check, shaders, assets, runtime and pipelines.",
      "  5. Run a build: it prints fixture lines and finishes without touching anything.",
      "",
      "To simulate upstream movement:",
      `  npm run mock:upstream -- --dest "${dest}" --add-commits 3`,
      "",
      readme.trim(),
    ].join("\n"),
  );
}

main().catch((error) => {
  fail(error instanceof Error ? error.message : String(error));
});
